/** 今の版（先頭のパッチノートの版） */
export const CURRENT_VERSION = PATCH_NOTES[0].version;

export function findPatchNote(version: string): PatchNote | null {
  return PATCH_NOTES.find((n) => n.version === version) ?? null;
}

/** 「2026/11/3」 */
export function patchNoteDateLabel(date: string): string {
  const [y, m, d] = date.split("-").map(Number);
  return `${y}/${m}/${d}`;
}
